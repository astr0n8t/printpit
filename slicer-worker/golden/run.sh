#!/bin/sh
# Golden test for the printpit-slicer image: real OrcaSlicer, real profiles, real G-code.
# The only test that runs Orca. It also guards the GUI-library stubs: if Orca ever calls into one,
# it aborts and this fails. Run it after every Orca bump.
#
# usage: slicer-worker/golden/run.sh <image>      (needs docker, curl, python3)
set -eu
image=${1:?usage: run.sh <image>}
name=printpit-slicer-golden-$$
work=$(mktemp -d)
token=$(od -An -N32 -tx1 /dev/urandom | tr -d ' \n')
cleanup() {
    status=$?
    [ "$status" -ne 0 ] && docker logs "$name" 2>&1 | tail -30 >&2
    docker rm -f "$name" >/dev/null 2>&1 || true
    rm -rf "$work"
}
trap cleanup EXIT
fail() { echo "FAIL: $*" >&2; exit 1; }
ok() { echo "ok: $*"; }

# As the compose files run it: read-only root, tmpfs work dir, no capabilities.
docker run -d --name "$name" --read-only --tmpfs /tmp:size=2g --cap-drop ALL \
    --security-opt no-new-privileges -e PRINTPIT_SLICER_TOKEN="$token" -p 127.0.0.1::8090 "$image" >/dev/null
url="http://$(docker port "$name" 8090/tcp | head -1)"
api() { curl -sS -H "Authorization: Bearer $token" "$@"; }

for _ in $(seq 1 60); do
    [ "$(api -o /dev/null -w '%{http_code}' "$url/v1/health" 2>/dev/null)" = 200 ] && break
    sleep 1
done
api -f "$url/v1/health" | grep -q '"status":"ok"' || fail "worker never became healthy"
docker exec "$name" /usr/local/bin/printpit-slicer healthcheck || fail "healthcheck subcommand"
[ "$(curl -sS -o /dev/null -w '%{http_code}' "$url/v1/health")" = 401 ] || fail "health without a token"
version=$(api -f "$url/v1/info" | python3 -c 'import json,sys; print(json.load(sys.stdin)["orca_version"])')
ok "healthy, OrcaSlicer $version"

enc() { python3 -c 'import sys, urllib.parse; print(urllib.parse.quote(sys.argv[1]))' "$1"; }
get_profile() { api -f -o "$work/$4" "$url/v1/profiles/$1/$(enc "$2")/$(enc "$3")" || fail "profile $1 $3"; }
get_profile machine Voron "Voron 2.4 350 0.4 nozzle" machine.json
get_profile process Voron "0.20mm Standard @Voron" process.json
get_profile filament Voron "Generic PLA @System" filament.json
api -f "$url/v1/vendors/Voron" | python3 -c '
import json, sys
v = json.load(sys.stdin)
assert any(m["name"] == "Voron 2.4 350 0.4 nozzle" for m in v["machines"]), "machine missing from index"
assert any(p["name"] == "0.20mm Standard @Voron" and p["compatible_printers"] for p in v["processes"])
' || fail "vendor index"
ok "system profiles and vendor index"

python3 - "$work/cube.stl" <<'EOF'
import struct, sys
s = 20.0
v = [(x * s, y * s, z * s) for x in (0, 1) for y in (0, 1) for z in (0, 1)]
quads = [(0, 2, 6, 4), (1, 5, 7, 3), (0, 4, 5, 1), (2, 3, 7, 6), (0, 1, 3, 2), (4, 6, 7, 5)]
tris = [t for a, b, c, d in quads for t in ((a, b, c), (a, c, d))]
with open(sys.argv[1], "wb") as f:
    f.write(b"printpit golden cube".ljust(80, b" ") + struct.pack("<I", len(tris)))
    for t in tris:
        f.write(struct.pack("<3f", 0, 0, 0) + b"".join(struct.pack("<3f", *v[i]) for i in t) + b"\0\0")
EOF

# slice <out> <machine> <process> <filament> <model> [options json] -> http status
slice() {
    set -- "$@" "${6:-{\}}"
    api -o "$work/$1" -D "$work/$1.headers" -w '%{http_code}' -X POST "$url/v1/slice" \
        -F "machine=<$work/$2" -F "process=<$work/$3" -F "filament=<$work/$4" \
        -F "options=$6" -F "model=@$work/$5"
}
header() { sed -n "s/^$2: *//Ip" "$work/$1.headers" | tr -d '\r'; }

start=$(date +%s)
[ "$(slice cube.gcode machine.json process.json filament.json cube.stl)" = 200 ] || fail "cube: $(cat "$work/cube.gcode")"
secs=$(( $(date +%s) - start ))
[ "$(header cube.gcode x-slice-layers)" = 100 ] || fail "cube layers: $(header cube.gcode x-slice-layers)"
[ "$(header cube.gcode x-slice-print-time-s)" -gt 60 ] || fail "cube print time"
grep -q "^; generated by OrcaSlicer $version" "$work/cube.gcode" || fail "not Orca's G-code"
grep -q "^EXCLUDE_OBJECT_DEFINE" "$work/cube.gcode" || fail "no EXCLUDE_OBJECT_DEFINE"
ok "20 mm cube: $(header cube.gcode x-slice-layers) layers, $(header cube.gcode x-slice-print-time-s) s," \
    "$(header cube.gcode x-slice-filament-g) g, $(wc -c < "$work/cube.gcode") bytes, ${secs}s round trip"

# User presets, as exported from Orca: differences only, `inherits` a system profile, renamed.
cat > "$work/presets.json" <<'EOF'
{"presets": [
  {"name": "Golden Voron", "from": "User", "inherits": "Voron 2.4 350 0.4 nozzle",
   "printer_settings_id": "Golden Voron", "retraction_length": ["0.65"]},
  {"name": "Golden 0.2", "from": "User", "inherits": "0.20mm Standard @Voron",
   "print_settings_id": "Golden 0.2", "sparse_infill_density": "35%"},
  {"name": "Golden PLA", "from": "User", "inherits": "Generic PLA @System",
   "filament_settings_id": ["Golden PLA"], "nozzle_temperature": ["213"]}
]}
EOF
api -f -X POST -H 'Content-Type: application/json' --data-binary "@$work/presets.json" \
    "$url/v1/profiles/resolve" > "$work/resolved.json" || fail "resolve"
python3 - "$work" <<'EOF' || fail "resolved presets"
import json, sys
work = sys.argv[1]
results = json.load(open(f"{work}/resolved.json"))["results"]
for r, out in zip(results, ("umachine.json", "uprocess.json", "ufilament.json")):
    assert "profile" in r, r
    json.dump(r["profile"], open(f"{work}/{out}", "w"))
EOF
[ "$(slice user.gcode umachine.json uprocess.json ufilament.json cube.stl)" = 200 ] || fail "user presets: $(cat "$work/user.gcode")"
grep -q "^; retraction_length = 0.65" "$work/user.gcode" || fail "machine override not applied"
grep -q "^; sparse_infill_density = 35%" "$work/user.gcode" || fail "process override not applied"
grep -q "^; nozzle_temperature = 213" "$work/user.gcode" \
    || fail "filament override not applied: $(grep -E '^; nozzle_temperature|^M10[49] ' "$work/user.gcode" | head -5)"
ok "user presets (resolved, renamed) slice with their overrides"

[ "$(slice arranged.gcode machine.json process.json filament.json cube.stl '{"arrange": true, "orient": true}')" = 200 ] \
    || fail "arrange/orient: $(cat "$work/arranged.gcode")"
ok "arrange + orient"

head -c 4096 /dev/urandom > "$work/junk.stl"
[ "$(slice junk.out machine.json process.json filament.json junk.stl)" = 422 ] || fail "junk model status"
grep -q '"kind":"model"' "$work/junk.out" || fail "junk model kind: $(cat "$work/junk.out")"
ok "a garbage model is a 422 model error"

[ -z "$(docker exec "$name" find /tmp -mindepth 1 -maxdepth 1 -name 'slice-*')" ] || fail "temp dirs left behind"
ok "no temp dirs left"
echo "golden: all passed"
