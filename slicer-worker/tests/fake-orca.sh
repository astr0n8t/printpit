#!/bin/sh
# A stand-in for `orca-slicer` in the worker's tests. The model file's first line picks what it does:
#   FAKE <mode> [record_dir]
# modes: ok, fail, exportfail, sleep, crash, noresult, nogcode. With a record_dir it copies its arguments,
# environment and the profiles it was given there, so tests can check them after the temp dir is gone.

for a in "$@"; do last=$a; done
if [ "$1" = "--help" ]; then
    echo "OrcaSlicer-9.9.9:"
    echo "Usage: orca-slicer [ OPTIONS ] [ file.3mf/file.stl ... ]"
    exit 0
fi

read -r magic mode record < "$last"
[ "$magic" = "FAKE" ] || { echo "not a fake model" >&2; exit 1; }
if [ -n "$record" ]; then
    printf '%s\n' "$@" > "$record/args.txt"
    env > "$record/env.txt"
    pwd > "$record/cwd.txt"
    for f in machine.json process.json filament.json; do [ -f "$f" ] && cp "$f" "$record/$f"; done
fi

plate=1; outdir=out; logfile=""
while [ $# -gt 0 ]; do
    case "$1" in
        --slice) plate=$2; shift ;;
        --outputdir) outdir=$2; shift ;;
        --logfile) logfile=$2; shift ;;
    esac
    shift
done

[ -n "$logfile" ] && echo "fake orca working in $PWD on $PWD/$last" >> "$logfile"
mkdir -p "$outdir"

case "$mode" in
    ok)
        {
            echo "; HEADER_BLOCK_START"
            echo "; generated by FakeSlicer"
            echo "; HEADER_BLOCK_END"
            echo ""
            echo "M83"
            # A 10 mm square, two layers, so printpit has something to draw.
            for z in 0.2 0.4; do
                echo ";LAYER_CHANGE"
                echo ";HEIGHT:0.2"
                echo "G1 Z$z"
                echo ";TYPE:Outer wall"
                echo ";WIDTH:0.45"
                echo "G0 X10 Y10"
                echo "G1 X20 Y10 E.5"
                echo "G1 X20 Y20 E.5"
                echo "G1 X10 Y20 E.5"
                echo "G1 X10 Y10 E.5"
            done
            echo "; filament used [mm] = 1304.61"
            echo "; filament used [g] = 3.89"
            echo "; total layers count = 100"
            echo "; estimated printing time (normal mode) = 9m 55s"
            echo "; CONFIG_BLOCK_START"
            echo "; printable_area = 0x0,100x0,100x100,0x100"
            echo "; thumbnails = 32x32/PNG,160x120/PNG"
            echo "; CONFIG_BLOCK_END"
        } > "$outdir/plate_$plate.gcode"
        echo '{"return_code": 0, "error_string": "Success."}' > "$outdir/result.json"
        ;;
    fail)
        echo '{"return_code": -6, "error_string": "The input model file to the slicer can not be parsed."}' > "$outdir/result.json"
        exit 250
        ;;
    exportfail)
        # What 2.5.1 does when the G-code export throws: a generic result.json, the reason on stderr.
        [ -n "$logfile" ] && echo "found slicing or export error for partplate $plate" >> "$logfile"
        {
            echo "Failed to generate G-code for invalid custom G-code."
            echo "machine_end_gcode Parsing error at line 4: Not a variable name"
            echo "G1 Z{nosuchvar} ; in $PWD"
            echo "     ^"
            echo "run found error, return -100, exit..."
        } >&2
        echo '{"return_code": -100, "error_string": "Failed slicing the model. Please verify the slicing of all plates on Orca Slicer before uploading."}' > "$outdir/result.json"
        exit 156
        ;;
    sleep)
        sleep 300 &
        [ -n "$record" ] && echo $! > "$record/child.pid" && echo $$ > "$record/self.pid"
        wait
        ;;
    crash)
        kill -ABRT $$
        ;;
    noresult)
        echo "something went wrong" >&2
        exit 3
        ;;
    nogcode)
        echo '{"return_code": 0, "error_string": "Success."}' > "$outdir/result.json"
        ;;
esac
